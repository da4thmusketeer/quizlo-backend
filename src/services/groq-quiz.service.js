import { groq } from "../lib/groq.js";
import { z } from "zod";

const QuizSchema = z.object({
  title: z.string(),
  questions: z.array(
    z.object({
      question: z.string(),
      options: z.array(z.string()).min(2),
      correctAnswer: z.number().int().min(0),
      explanation: z.string().optional().default(""),
    })
  ),
});

export async function generateAIQuiz({
  topic,
  difficulty = "Medium",
  numberOfQuestions = 5,
}) {
  const model = process.env.GROQ_MODEL || "llama-3.3-70b-versatile";

  const prompt = `
Generate a ${difficulty} difficulty quiz about "${topic}".

Requirements:
- Exactly ${numberOfQuestions} questions
- Four options per question
- One correct answer per question
- correctAnswer must be the 0-based index (0, 1, 2, or 3) of the correct option in the options array
- Include a short explanation for each answer
- Return only valid JSON

Format:
{
  "title": "Quiz title",
  "questions": [
    {
      "question": "Question text",
      "options": ["Option A", "Option B", "Option C", "Option D"],
      "correctAnswer": 0,
      "explanation": "Explanation for the correct answer"
    }
  ]
}
`;

  const completion = await groq.chat.completions.create({
    model,
    messages: [
      {
        role: "system",
        content: "You generate accurate educational quizzes. Always return valid JSON matching the requested structure.",
      },
      { role: "user", content: prompt },
    ],
    temperature: 0.3,
    response_format: { type: "json_object" },
  });

  const content = completion.choices[0]?.message?.content;

  if (!content) {
    throw new Error("No quiz generated by AI service");
  }

  // Defensive strip of any markdown code blocks if present
  const cleanedContent = content.trim().replace(/^```(?:json)?\s*/i, "").replace(/\s*```$/, "");
  const parsedData = JSON.parse(cleanedContent);
  const quiz = QuizSchema.parse(parsedData);

  if (quiz.questions.length > numberOfQuestions) {
    quiz.questions = quiz.questions.slice(0, numberOfQuestions);
  } else if (quiz.questions.length === 0) {
    throw new Error("AI failed to generate quiz questions");
  }

  return quiz;
}